export function videosByPos(pos: PositionId) {
  return POSITION_VIDEOS.filter((v) => v.pos === pos);
}
export function findVideo(pos: string, slug: string) {
  return POSITION_VIDEOS.find((v) => v.pos === pos && v.slug === slug);
}
export const videoPath = (v: PositionVideo) => `/position/${v.pos}/${v.slug}`;
